use anyhow::{Context, Result, ensure};
use std::{fs, path::Path};

fn main() -> Result<()> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    ensure!(
        args.is_empty() || args == ["--check"],
        "usage: cargo run -- [--check]"
    );
    let check = !args.is_empty();
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    for name in ["open-data", "public-data"] {
        let spec_path = root.join(format!("{name}/openapi.yaml"));
        let spec: openapiv3::OpenAPI = serde_yaml_ng::from_str(&fs::read_to_string(&spec_path)?)
            .with_context(|| format!("reading {}", spec_path.display()))?;
        for raw in [false, true] {
            let mut contract = spec.clone();
            if raw {
                // Derive streaming responses from the canonical contract. No
                // second specification or hand-maintained endpoint list.
                for path in contract.paths.paths.values_mut() {
                    if let openapiv3::ReferenceOr::Item(path) = path {
                        for operation in [
                            &mut path.get,
                            &mut path.put,
                            &mut path.post,
                            &mut path.delete,
                            &mut path.options,
                            &mut path.head,
                            &mut path.patch,
                            &mut path.trace,
                        ]
                        .into_iter()
                        .flatten()
                        {
                            for (status, response) in operation.responses.responses.iter_mut() {
                                if matches!(status, openapiv3::StatusCode::Code(200))
                                    && let openapiv3::ReferenceOr::Item(response) = response
                                {
                                    response.content.clear();
                                    response.content.insert(
                                        "application/octet-stream".into(),
                                        openapiv3::MediaType::default(),
                                    );
                                }
                            }
                        }
                    }
                }
            }
            let settings = progenitor::GenerationSettings::default();
            let mut generator = progenitor::Generator::new(&settings);
            let tokens = generator
                .generate_tokens(&contract)
                .with_context(|| format!("generating {name}, streaming={raw}"))?;
            let ast = syn::parse2(tokens)?;
            let source = format!(
                "// Generated by Progenitor 0.16.0 from {name}/openapi.yaml. Do not edit.\n{}",
                prettyplease::unparse(&ast)
            );
            let filename = if raw { "raw.rs" } else { "generated.rs" };
            let output = root.join(format!("{name}/rust/src/{filename}"));
            if check {
                ensure!(
                    fs::read_to_string(&output).ok().as_deref() == Some(source.as_str()),
                    "{} is stale; run just generate from the repository root",
                    output.display()
                );
            } else {
                fs::write(&output, source)?;
            }
            println!(
                "{} {name}/{filename}",
                if check { "verified" } else { "generated" }
            );
        }
    }
    Ok(())
}
